function translatePage(lang) {
    if (!translations[lang]) {
        console.error(`Language ${lang} not found in translations object`);
        return;
    }

    document.querySelectorAll('[data-translate]').forEach(element => {
        const key = element.getAttribute('data-translate');
        if (translations[lang][key]) {
            element.textContent = translations[lang][key];
        } else {
            console.warn(`Translation key ${key} not found for language ${lang}`);
        }
    });

    // Update RTL/LTR direction
    const isRtl = (lang === 'ar' || lang === 'dv');
    document.documentElement.dir = isRtl ? 'rtl' : 'ltr';
    if (isRtl) {
        document.body.classList.add('rtl');
    } else {
        document.body.classList.remove('rtl');
    }

    // Reinitialize sliders with new direction
    initSliders();

    // Update language toggle button
    const langToggle = document.getElementById('language-toggle');
    if (langToggle) {
        langToggle.querySelector('span').textContent = lang.toUpperCase();
    }

    // Dispatch language change event for globe
    const languageChangeEvent = new Event('languageChange');
    window.dispatchEvent(languageChangeEvent);
}


function makeFlagEl(country) {
    const wrap = document.createElement('div'); // Wrapper for globe positioning
    wrap.style.pointerEvents = 'none'; // Prevent wrapper from intercepting events
    wrap.style.direction = 'ltr'; // Force LTR
    wrap.style.unicodeBidi = 'isolate'; // Isolate text direction
    const el = document.createElement('img'); // Flag image
    el.crossOrigin = 'anonymous';
    el.src = flagUrls[country.code];
    el.alt = `Flag of ${country.name}`;
    el.style.width = '32px';
    el.style.height = '24px';
    el.style.cursor = 'pointer';
    el.style.zIndex = '10'; // Ensure above canvas
    el.style.transform = 'translate(-50%, -100%)'; // Anchor flag above point
    el.style.pointerEvents = 'auto'; // Enable clicks on flag
    el.style.direction = 'ltr'; // Force LTR for flag
    el.style.unicodeBidi = 'isolate'; // Isolate text direction
    el.onerror = () => {
        el.src = localFallbackUrls[country.code] || '/images/flags/xx.webp';
    };
    el.addEventListener('click', e => {
        e.stopPropagation();
        const pageUrl = countryPageMap[country.code] || `${country.code.toLowerCase()}.html`;
        window.location.href = pageUrl;
    });
    el.tabIndex = 0;
    el.addEventListener('keydown', e => {
        if (e.key === 'Enter' || e.key === ' ') {
            e.preventDefault();
            e.stopPropagation();
            const pageUrl = countryPageMap[country.code] || `${country.code.toLowerCase()}.html`;
            window.location.href = pageUrl;
        }
    });
    wrap.appendChild(el);
    return wrap;
}






        // Language Selector Logic
      document.addEventListener('DOMContentLoaded', () => {
        const languageToggle = document.getElementById('language-toggle');
        const languageDropdown = document.querySelector('.language-dropdown');
        const languageSelector = document.querySelector('.language-selector');

        if (!languageToggle || !languageDropdown) {
            console.error('Language toggle or dropdown not found');
            return;
        }

        // Toggle dropdown on click
        languageToggle.addEventListener('click', (e) => {
            e.preventDefault();
            languageSelector.classList.toggle('active');
            languageDropdown.style.display = languageSelector.classList.contains('active') ? 'block' : 'none';
        });

        // Close dropdown when clicking outside
        document.addEventListener('click', (e) => {
            if (!languageToggle.contains(e.target) && !languageDropdown.contains(e.target)) {
                languageSelector.classList.remove('active');
                languageDropdown.style.display = 'none';
            }
        });

        // Language selection
        document.querySelectorAll('.language-dropdown a').forEach(link => {
            link.addEventListener('click', function(e) {
                e.preventDefault();
                const lang = this.getAttribute('data-lang');
                console.log(`Switching to language: ${lang}`);
                setLanguage(lang);
                languageSelector.classList.remove('active');
                languageDropdown.style.display = 'none';
            });
        });

        initSliders();
        initGlobe();
        initLanguage();
    });
